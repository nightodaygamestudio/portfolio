function goToStage(index) {
  const clamped = Math.max(0, Math.min(3, index));
  currentStageIdx = clamped;

  const track = document.getElementById("horizontal-track");
  if (track) {
    track.style.transform = `translate3d(-${clamped * 100}vw, 0, 0)`;
  }

  // Hide Top HUD Header on Stage 0 (Showreel), show from Stage 1 (About Me) onwards
  const hudHeader = document.getElementById("hud-header");
  if (hudHeader) {
    hudHeader.classList.toggle("is-hidden", clamped === 0);
  }

  // Shift starfield parallax seamlessly using unwrapped orbit steps
  starfieldTargetOffsetX = clamped * 260 + cumulativeOrbitSteps * 55;

  // Update Top HUD Stage Tabs
  const tabIds = ["nav-showreel", "nav-about", "nav-origin", "nav-orbit"];
  tabIds.forEach((id, idx) => {
    const el = document.getElementById(id);
    if (el) el.classList.toggle("active", idx === clamped);
  });

  // Update Footer Progress Bar (0% on Stage 0 Showreel, fills from Stage 1 About Me onwards)
  const progressFill = document.getElementById("stage-progress-fill");
  if (progressFill) {
    progressFill.style.width = `${(clamped / 3) * 100}%`;
  }
}

